export function getProvinceInfo(nameTh:string, region:Region, description:string, bestMonths:string[]):ProvinceInfo{
  const base=REGION_DEFAULTS[region];
  const curated=CURATED[nameTh];
  const highlights=curated?.highlights || ['แลนด์มาร์กและจุดชมวิวของจังหวัด','ชุมชนและวัฒนธรรมท้องถิ่น','ร้านอาหาร คาเฟ่ และตลาดท้องถิ่น'];
  const localFoods=curated?.foods || ['อาหารท้องถิ่น','ของฝากประจำจังหวัด','ร้านพื้นบ้าน'];
  return {
    ...base,
    shortSummary:`${nameTh} • ${region} • ${base.bestFor.slice(0,2).join(' • ')}`,
    fullDescription:`${description} หน้านี้รวบรวมข้อมูลเที่ยวที่จำเป็นสำหรับวางแผนทริป ทั้งไฮไลต์ ช่วงเวลาที่เหมาะ แนวทางเดินทาง อาหารและของฝาก รวมถึงสถานที่ที่มีข้อมูลอยู่ในระบบ`,
    highlights,
    localFoods,
    seasonNote:`${base.seasonNote} ช่วงที่ระบบแนะนำ: ${bestMonths.join(', ')}`
  };
}
