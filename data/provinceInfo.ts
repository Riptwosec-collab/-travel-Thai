export function getProvinceInfo(nameTh:string, region:Region, description:string, bestMonths:string[]):ProvinceInfo{
  const base=REGION_DEFAULTS[region];
  const unique=UNIQUE[nameTh];
  const highlights=unique?.highlights || ['จุดชมธรรมชาติและแลนด์มาร์กของจังหวัด','ย่านชุมชนและวัฒนธรรมท้องถิ่น','ร้านอาหารและคาเฟ่ท้องถิ่น'];
  const foods=unique?.foods || ['อาหารท้องถิ่น','ของฝากประจำจังหวัด','ร้านพื้นบ้าน'];
  return {
    ...base,
    shortSummary: unique?.summary || `${nameTh} • ${region} • เหมาะกับ ${base.bestFor.slice(0,2).join(' และ ')}`,
    fullDescription: `${description} ในหน้าแผนที่จะแสดงข้อมูลสรุปเพื่อเลือกจุดหมายอย่างรวดเร็ว และเมื่อเปิดรายละเอียดจะเห็นไฮไลต์ ช่วงเที่ยวที่แนะนำ แนวทางเดินทาง อาหาร และสถานที่ที่มีในระบบ`,
    highlights,
    localFoods:foods,
    seasonNote:`${base.seasonNote} ช่วงแนะนำในระบบ: ${bestMonths.join(', ')}`
  };
}
